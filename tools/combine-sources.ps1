<#
.SYNOPSIS
    Combines the intro's C sources and GLSL shaders into a single UTF-8 text file.

.DESCRIPTION
    Order: main.c, other *.c, *.h (alphabetical), then shd/*.hlsl.
    Each file is preceded by a header with its repository-relative path.
    Files are read as UTF-8 when valid, otherwise as Windows-1251 (legacy comments),
    and the result is always written as UTF-8 without BOM.

    Headers generated by Shader Minifier (vhlsl.h, fhlsl.h, ...) duplicate shd/*.hlsl
    and are skipped unless -IncludeGenerated is given. Third-party inc/ is never included.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\combine-sources.ps1
    powershell -ExecutionPolicy Bypass -File tools\combine-sources.ps1 -Output all.txt -IncludeGenerated
#>
param(
    [string]$Output = 'build\sources.txt',
    [switch]$IncludeGenerated
)

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$srcDir = Join-Path $root 'src\nodefaultlib-4k'
$shdDir = Join-Path $root 'shd'

$strictUtf8 = New-Object System.Text.UTF8Encoding($false, $true)
$cp1251 = [System.Text.Encoding]::GetEncoding(1251)

function Read-SourceText([string]$path) {
    $bytes = [System.IO.File]::ReadAllBytes($path)
    $offset = 0
    if ($bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF) {
        $offset = 3
    }
    try {
        return $strictUtf8.GetString($bytes, $offset, $bytes.Length - $offset)
    }
    catch [System.Text.DecoderFallbackException] {
        return $cp1251.GetString($bytes)
    }
}

function Test-Generated([string]$text) {
    return $text -match 'File generated with Shader Minifier'
}

$cFiles = Get-ChildItem $srcDir -Filter *.c | Sort-Object { $_.Name -ne 'main.c' }, Name
$hFiles = Get-ChildItem $srcDir -Filter *.h | Sort-Object Name
$shaders = Get-ChildItem $shdDir -Filter *.hlsl | Sort-Object Name

$builder = New-Object System.Text.StringBuilder
$included = 0
$skipped = @()

foreach ($file in @($cFiles) + @($hFiles) + @($shaders)) {
    $text = Read-SourceText $file.FullName
    if (-not $IncludeGenerated -and $file.Extension -eq '.h' -and (Test-Generated $text)) {
        $skipped += $file.Name
        continue
    }
    $relative = $file.FullName.Substring($root.Length + 1).Replace('\', '/')
    [void]$builder.AppendLine("// ==================== $relative ====================")
    [void]$builder.AppendLine($text.TrimEnd())
    [void]$builder.AppendLine()
    $included++
}

$outPath = if ([System.IO.Path]::IsPathRooted($Output)) { $Output } else { Join-Path $root $Output }
$outDir = Split-Path -Parent $outPath
if (-not (Test-Path $outDir)) { New-Item -ItemType Directory -Path $outDir | Out-Null }
[System.IO.File]::WriteAllText($outPath, $builder.ToString(), (New-Object System.Text.UTF8Encoding($false)))

Write-Host "Combined $included files -> $outPath"
if ($skipped.Count -gt 0) {
    Write-Host "Skipped generated shader headers (use -IncludeGenerated): $($skipped -join ', ')"
}
